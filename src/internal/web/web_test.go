// newTestServer 起一个完整的服务（随机端口），返回 server 与 baseURL。
func newTestServer(t *testing.T, mutate func(*config.Config)) (*Server, string) {
	t.Helper()
	lg, err := logging.New("error", t.TempDir(), 200, 8)
	if err != nil {
		t.Fatal(err)
	}
	// LIFO：先注册的 Close 后执行——Shutdown 完才关日志文件，
	// 否则 Windows 上文件句柄未释放，TempDir 清理会失败。
	t.Cleanup(func() { _ = lg.Close() })

	cfgPath := filepath.Join(t.TempDir(), "mergence.json")
	cfg := config.Default()
	if mutate != nil {
		mutate(cfg)
	}
	reg := provider.NewRegistry(lg)
	orch := orchestrator.New(t.TempDir(), lg)
	s := New(lg, orch, reg, t.TempDir())
	s.SetConfig(cfg, cfgPath)
	port, err := s.Start()
	if err != nil {
		t.Fatalf("启动失败：%v", err)
	}
	t.Cleanup(func() {
		ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
		defer cancel()
		s.Shutdown(ctx)
	})
	return s, "http://127.0.0.1:" + itoa(port)
}

// waitClosed 轮询等待端口关闭（旧监听器是异步优雅关闭的）。
func waitClosed(t *testing.T, port int) {
	t.Helper()
	deadline := time.Now().Add(3 * time.Second)
	for time.Now().Before(deadline) {
		conn, err := net.DialTimeout("tcp",
			net.JoinHostPort("127.0.0.1", strconv.Itoa(port)), 300*time.Millisecond)
		if err != nil {
			return // 连不上 = 已关闭
		}
		conn.Close()
		time.Sleep(100 * time.Millisecond)
	}
	t.Fatalf("端口 %d 在 3s 内未关闭", port)
}

// itoa 不引 strconv 就为了一个数字转换——测试文件里保持轻量。
func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	neg := n < 0
	if neg {
		n = -n
	}
	var b [20]byte
	i := len(b)
	for n > 0 {
		i--
		b[i] = byte('0' + n%10)
		n /= 10
	}
	if neg {
		i--
		b[i] = '-'
	}
	return string(b[i:])
}

func TestAccessKeyAutoGeneratedAndEnforced(t *testing.T) {
	s, base := newTestServer(t, nil)

	key := s.currentAccessKey()
	if key == "" {
		t.Fatal("normalize 应自动生成 access_key")
	}
	if len(key) != 32 {
		t.Errorf("Key 应为 32 位十六进制（128 位熵），得到 %d 位", len(key))
	}

	// 无 Key → 401（OpenAI 错误格式）
	resp, err := http.Get(base + "/v1/models")
	if err != nil {
		t.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusUnauthorized {
		t.Errorf("无 Key 访问 /v1/models 应 401，得到 %d", resp.StatusCode)
	}

	// 错 Key → 401
	req, _ := http.NewRequest("GET", base+"/v1/models", nil)
	req.Header.Set("Authorization", "Bearer wrong-key")
	resp2, err := http.DefaultClient.Do(req)
	if err != nil {
		t.Fatal(err)
	}
	resp2.Body.Close()
	if resp2.StatusCode != http.StatusUnauthorized {
		t.Errorf("错 Key 应 401，得到 %d", resp2.StatusCode)
	}

	// 正确 Key → 200（列表可为空，但接口本身应放行）
	req3, _ := http.NewRequest("GET", base+"/v1/models", nil)
	req3.Header.Set("Authorization", "Bearer "+key)
	resp3, err := http.DefaultClient.Do(req3)
	if err != nil {
		t.Fatal(err)
	}
	resp3.Body.Close()
	if resp3.StatusCode != http.StatusOK {
		t.Errorf("正确 Key 应 200，得到 %d", resp3.StatusCode)
	}

	// X-API-Key 头也应放行
	req4, _ := http.NewRequest("GET", base+"/v1/models", nil)
	req4.Header.Set("X-API-Key", key)
	resp4, err := http.DefaultClient.Do(req4)
	if err != nil {
		t.Fatal(err)
	}
	resp4.Body.Close()
	if resp4.StatusCode != http.StatusOK {
		t.Errorf("X-API-Key 应放行，得到 %d", resp4.StatusCode)
	}

	// 面板接口不受 Key 保护（本机控制面）
	resp5, err := http.Get(base + "/api/status")
	if err != nil {
		t.Fatal(err)
	}
	resp5.Body.Close()
	if resp5.StatusCode != http.StatusOK {
		t.Errorf("面板 /api/status 不应要求 Key，得到 %d", resp5.StatusCode)
	}
}

func TestAccessKeyRegenerate(t *testing.T) {
	s, base := newTestServer(t, nil)
	old := s.currentAccessKey()

	resp, err := http.Post(base+"/api/access-key/regenerate", "application/json", nil)
	if err != nil {
		t.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("重新生成应 200，得到 %d", resp.StatusCode)
	}
	var d struct {
		OK        bool   `json:"ok"`
		AccessKey string `json:"access_key"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&d); err != nil {
		t.Fatal(err)
	}
	if !d.OK || d.AccessKey == "" || d.AccessKey == old {
		t.Fatalf("应返回新的非空 Key（old=%q new=%q）", old, d.AccessKey)
	}
	if s.currentAccessKey() != d.AccessKey {
		t.Error("服务端当前 Key 应立即更新")
	}

	// 旧 Key 立即失效
	req, _ := http.NewRequest("GET", base+"/v1/models", nil)
	req.Header.Set("Authorization", "Bearer "+old)
	resp2, err := http.DefaultClient.Do(req)
	if err != nil {
		t.Fatal(err)
	}
	resp2.Body.Close()
	if resp2.StatusCode != http.StatusUnauthorized {
		t.Errorf("旧 Key 应立即 401，得到 %d", resp2.StatusCode)
	}
}

