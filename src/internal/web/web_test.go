// TestAdminKeyAcceptsNativeChannel 原生（进程内）渠道同样有独立网关设置，
// 改密接口必须接受它。旧判据是 `up.Source != "managed"`，会把所有原生渠道挡成
// 501 not_managed —— 子进程模式移除后每个托管渠道都是原生型，那等于这个功能
// 整体失效。判据必须是 Hosted()。
func TestAdminKeyAcceptsNativeChannel(t *testing.T) {
	var gotPath, gotAuth atomic.Value
	up := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		gotPath.Store(r.URL.Path)
		gotAuth.Store(r.Header.Get("Authorization"))
		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(200)
		_, _ = w.Write([]byte(`{"ok":true}`))
	}))
	defer up.Close()

	s, base := newTestServer(t, func(c *config.Config) {
		c.Managed = append(c.Managed, config.ManagedProvider{
			Name: "zc", DisplayName: "zc", Enabled: true,
			// Mode=native ⇒ FromManaged 产出的 Source 就是 SourceNative。
			Kind: "zcode", Mode: config.ModeNative,
			Route: &config.RouteSpec{APIKey: "old-key", ModelPrefix: "zcode-"},
		})
	})
	u := provider.FromManaged(s.currentConfig().Managed[0], up.URL, true, "")
	if u.Source != provider.SourceNative {
		t.Fatalf("Mode=native 应产出 SourceNative，得到 %q", u.Source)
	}
	u.RootURL = up.URL
	s.reg.Reload([]provider.Upstream{u})

	resp, err := http.Post(base+"/api/channels/admin-key", "application/json",
		strings.NewReader(`{"name":"zc","admin_key":"new-key"}`))
	if err != nil {
		t.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode == http.StatusNotImplemented {
		t.Fatalf("原生渠道不该被判为 not_managed（得到 501）")
	}
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("改密应 200，得到 %d", resp.StatusCode)
	}
	// zcode 的管理 API 前缀是 /admin/api（不是 /panel/api）
	if got, _ := gotPath.Load().(string); got != "/admin/api/settings" {
		t.Errorf("应打到 zcode 的 /admin/api/settings，得到 %q", got)
	}
	if got, _ := gotAuth.Load().(string); got != "Bearer old-key" {
		t.Errorf("应用渠道旧 route key 鉴权，得到 %q", got)
	}
	// route key 是后台密码的真源：新值必须落盘到渠道配置
	var saved string
	for _, m := range s.currentConfig().Managed {
		if m.Name == "zc" && m.Route != nil {
			saved = m.Route.APIKey
		}
	}
	if saved != "new-key" {
		t.Errorf("route key 应同步为新值，得到 %q", saved)
	}
}

func TestProxyForwardsToManagedUpstream(t *testing.T) {
	// 假上游：模拟 wb2api 的 /panel/api/overview，校验 Bearer 注入
	var gotAuth atomic.Value
	up := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		gotAuth.Store(r.Header.Get("Authorization"))
		if !strings.HasSuffix(r.URL.Path, "/panel/api/overview") {
			http.Error(w, "not found", http.StatusNotFound)
			return
		}
		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(200)
		_, _ = w.Write([]byte(`{"total":2,"healthy":2,"accounts":[{"uid":"u1","nickname":"A","credits":10}]}`))
	}))
	defer up.Close()
	// httptest 的 URL 形如 http://127.0.0.1:port；拆出根地址
	root := strings.TrimSuffix(up.URL, "/v1")

	s, base := newTestServer(t, func(c *config.Config) {
		c.Managed = append(c.Managed, config.ManagedProvider{
			Name: "m1", DisplayName: "m1", Enabled: true,
			PanelAPIPrefix: "/panel/api",
			Route: &config.RouteSpec{
				APIKey: "upstream-secret", ModelPrefix: "m/",
			},
		})
	})
	// 直接注册一个就绪的托管型上游（不真起子进程——代理不关心子进程，只关心地址）
	upstream := provider.FromManaged(
		s.currentConfig().Managed[0], root, true, "")
	// FromManaged 会拼 /v1 前缀；把它改回根地址 + 覆盖 RootURL
	upstream.BaseURL = root + "/v1"
	upstream.RootURL = root
	s.reg.Reload([]provider.Upstream{upstream})

	resp, err := http.Get(base + "/api/channels/m1/upstream/overview")
	if err != nil {
		t.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("代理应 200，得到 %d", resp.StatusCode)
	}
	var d struct {
		Total    int `json:"total"`
		Accounts []struct {
			UID string `json:"uid"`
		} `json:"accounts"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&d); err != nil {
		t.Fatal(err)
	}
	if d.Total != 2 || len(d.Accounts) != 1 || d.Accounts[0].UID != "u1" {
		t.Errorf("代理应原样透传上游响应，得到 %+v", d)
	}
	if got, _ := gotAuth.Load().(string); got != "Bearer upstream-secret" {
		t.Errorf("代理应注入渠道的 Bearer Key，得到 %q", got)
	}
}

func TestPortHotSwitch(t *testing.T) {
	s, base := newTestServer(t, nil)
	oldPort := s.Port()

	// 切到新端口
	body := strings.NewReader(`{"port": 0}`) // 0 = 动态，必定成功且不同于当前
	resp, err := http.Post(base+"/api/settings/port", "application/json", body)
	if err != nil {
		t.Fatal(err)
	}
	var d struct {
		OK      bool   `json:"ok"`
		BaseURL string `json:"base_url"`
		Port    int    `json:"port"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&d); err != nil {
		t.Fatal(err)
	}
	resp.Body.Close()
	if !d.OK || d.Port == 0 || d.Port == oldPort {
		t.Fatalf("应切换到新的动态端口，得到 port=%d（旧 %d）", d.Port, oldPort)
	}
	if s.Port() != d.Port {
		t.Errorf("Server.Port 应更新，得到 %d want %d", s.Port(), d.Port)
	}
	// 新端口上服务应可用
	resp2, err := http.Get(d.BaseURL + "/api/healthz")
	if err != nil {
		t.Fatalf("新端口不可访问：%v", err)
	}
	resp2.Body.Close()
	if resp2.StatusCode != http.StatusOK {
		t.Errorf("新端口 healthz 应 200，得到 %d", resp2.StatusCode)
	}
	// 旧端口应已关闭（异步优雅关闭，轮询等待）
	waitClosed(t, oldPort)

	// 配置应落盘
	if got := s.currentConfig().Ports.PanelPort; got != 0 {
		t.Errorf("动态模式 PanelPort 应为 0，得到 %d", got)
	}
}

func TestPortHotSwitchConflict(t *testing.T) {
	s, base := newTestServer(t, nil)

	// 占住一个端口
	blocker, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer blocker.Close()
	busy := blocker.Addr().(*net.TCPAddr).Port

	payload := strings.NewReader(`{"port": ` + itoa(busy) + `}`)
	resp, err := http.Post(base+"/api/settings/port", "application/json", payload)
	if err != nil {
		t.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusConflict {
		t.Errorf("占用端口应 409，得到 %d", resp.StatusCode)
	}
	// 原服务不受影响
	if s.Port() == busy {
		t.Error("失败时不应改变端口")
	}
	resp2, err := http.Get(base + "/api/healthz")
	if err != nil {
		t.Fatalf("原服务应继续可用：%v", err)
	}
	resp2.Body.Close()
}
