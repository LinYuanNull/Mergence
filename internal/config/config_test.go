func TestDefaultsApplied(t *testing.T) {
	c := parseOne(t, []EmbeddedProvider{{
		Name: "a", BaseURL: "https://a.b/", Enabled: true,
	}})
	e := c.Embedded[0]
	if e.Protocol != "chat" {
		t.Errorf("protocol 默认 = %q", e.Protocol)
	}
	if e.Weight != 1 {
		t.Errorf("weight 默认 = %d", e.Weight)
	}
	if e.ModelSource != "auto" {
		t.Errorf("model_source 默认 = %q", e.ModelSource)
	}
	if e.DisplayName != "a" {
		t.Errorf("display_name 应回落为 name：%q", e.DisplayName)
	}
	if strings.HasSuffix(e.BaseURL, "/") {
		t.Errorf("base_url 结尾斜杠应被去掉：%q", e.BaseURL)
	}
	if e.HealthPath == "" {
		t.Error("health_path 应补默认值")
	}
	if e.TimeoutDuration().Seconds() != 120 {
		t.Errorf("超时默认 = %v", e.TimeoutDuration())
	}
}

