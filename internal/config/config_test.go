func parseOne(t *testing.T, embedded []EmbeddedProvider) *Config {
	t.Helper()
	c := Default()
	c.Embedded = embedded
	raw, err := json.Marshal(c)
	if err != nil {
		t.Fatalf("序列化失败：%v", err)
	}
	got, _, err := Parse(raw)
	if err != nil {
		t.Fatalf("Parse 失败：%v", err)
	}
	return got
}

func TestModelListAcceptsBothForms(t *testing.T) {
	raw := []byte(`{
	  "embedded_providers": [{
	    "name": "x", "base_url": "https://a.b/v1",
	    "models": ["plain-id", {"id": "obj-id", "alias": "al", "context": 8192}]
	  }]
	}`)
	c, _, err := Parse(raw)
	if err != nil {
		t.Fatalf("Parse 失败：%v", err)
	}
	ms := c.Embedded[0].Models
	if len(ms) != 2 {
		t.Fatalf("模型数 = %d：%+v", len(ms), ms)
	}
	if ms[0].ID != "plain-id" || ms[0].Outward() != "plain-id" {
		t.Errorf("简写形式解析错误：%+v", ms[0])
	}
	if ms[1].ID != "obj-id" || ms[1].Outward() != "al" || ms[1].Context != 8192 {
		t.Errorf("完整形式解析错误：%+v", ms[1])
	}
}

