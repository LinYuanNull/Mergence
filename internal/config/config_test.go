func TestPrefixAutoGenerated(t *testing.T) {
	c := parseOne(t, []EmbeddedProvider{
		{Name: "OpenRouter", BaseURL: "https://a.b", Enabled: true},
		{Name: "智谱 BigModel", BaseURL: "https://c.d", Enabled: true},
		{Name: "幻方量化", BaseURL: "https://e.f", Enabled: true},
	})
	if got := c.Embedded[0].ModelPrefix; got != "openrouter-" {
		t.Errorf("英文名应生成 slug 前缀，得到 %q", got)
	}
	// 中英混排：取其中的 ASCII 部分，比哈希可读得多
	if got := c.Embedded[1].ModelPrefix; got != "bigmodel-" {
		t.Errorf("中英混排应取 ASCII 片段，得到 %q", got)
	}
	// 纯中文取不出 ASCII → 退化为稳定哈希，但必须唯一且可路由
	zh := c.Embedded[2].ModelPrefix
	// 前缀不带尾斜杠（用户要求去掉 `/`），但要以 `-` 收尾保证边界可辨
	if !strings.HasSuffix(zh, "-") || strings.HasSuffix(zh, "/") ||
		!strings.HasPrefix(zh, "ch") {
		t.Fatalf("纯中文名应退化为 ch 前缀（以 - 收尾），得到 %q", zh)
	}
	if zh == c.Embedded[1].ModelPrefix {
		t.Fatalf("两个渠道的前缀不应相同：%q", zh)
	}
}

func TestPrefixCollisionDisablesLater(t *testing.T) {
	// 两条都显式指定同一个前缀：路由会歧义，必须禁掉后者而不是静默取第一个
	c := parseOne(t, []EmbeddedProvider{
		{Name: "a", BaseURL: "https://a.b", Enabled: true, ModelPrefix: "same"},
		{Name: "b", BaseURL: "https://c.d", Enabled: true, ModelPrefix: "same"},
	})
	if !c.Embedded[0].Enabled {
		t.Error("第一个渠道应保持启用")
	}
	if c.Embedded[1].Enabled {
		t.Error("前缀重复的渠道必须被禁用，否则请求会被送到错误的上游")
	}
	// 用户填的前缀语义不改，只补分隔符（`same` → `same-`），
	// 否则拼出来是 `samex-model`，前缀边界不可辨
	if c.Embedded[1].ModelPrefix != "same-" {
		t.Errorf("不应改写用户填的前缀语义：%q", c.Embedded[1].ModelPrefix)
	}
	// 存量配置里的尾斜杠要被剥掉，拼接时不再出现 `old/x` 这种形态
	c2 := parseOne(t, []EmbeddedProvider{
		{Name: "a", BaseURL: "https://a.b", Enabled: true, ModelPrefix: "old/"},
	})
	if got := c2.Embedded[0].ModelPrefix; got != "old-" {
		t.Errorf("存量配置的尾斜杠应被剥掉并补分隔符，得到 %q", got)
	}
	// 用户已自带分隔符的，不再多补
	c3 := parseOne(t, []EmbeddedProvider{
		{Name: "a", BaseURL: "https://a.b", Enabled: true, ModelPrefix: "wb-"},
	})
	if got := c3.Embedded[0].ModelPrefix; got != "wb-" {
		t.Errorf("已带 - 的前缀不应被改写：%q", got)
	}
}

